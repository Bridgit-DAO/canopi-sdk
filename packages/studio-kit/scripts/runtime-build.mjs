// Bundles src/runtime.ts into one dependency-free ES module (the studio-kit.js of every
// scaffolded tablication). Shared by gen-runtime.mjs and the freshness test.
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const RUNTIME_ENTRY = path.join(pkg, 'src/runtime.ts');
export const RUNTIME_OUT = path.join(pkg, 'src/generated/runtime-source.ts');

export async function buildRuntimeModule() {
  const r = await build({ absWorkingDir: pkg, entryPoints: [RUNTIME_ENTRY], bundle: true, format: 'esm', platform: 'browser', target: 'es2020', write: false, legalComments: 'none', charset: 'utf8', logLevel: 'silent' });
  const code = `// @canopi-sdk/studio-kit runtime: sidebar renderers, data sources, bindings. Generated; do not edit.\n${r.outputFiles[0].text}`;
  return `/* eslint-disable */\n// Generated by scripts/gen-runtime.mjs from src/runtime.ts. Do not edit; run \`npm run gen:runtime -w packages/studio-kit\`.\nexport const RUNTIME_SOURCE: string = ${JSON.stringify(code)};\n`;
}
